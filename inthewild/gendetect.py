"""Generated-file detection rules for the AIDev in-the-wild study.

Two independent detectors:
  (a) PATH conventions (file name / directory patterns emitted by widely used generators);
  (b) HEADER markers in the first 15 lines of the file (taken from patch text, or from fetched content).
Lockfiles are a separate category and are never counted as "generated" by (a) or (b).
Also: plausible-source rules used to decide whether a PR that edits a generated file also edits
something the generated file could have been produced from.
"""
import os, re

# ---------------- lockfiles (separate category) ----------------
LOCKFILES = {"package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
             "poetry.lock", "Pipfile.lock", "uv.lock", "pdm.lock", "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock",
             "flake.lock", "Podfile.lock", "Package.resolved", "packages.lock.json", "gradle.lockfile", "mix.lock",
             "pubspec.lock", "deno.lock", "conda-lock.yml", "pixi.lock", "renv.lock", "Manifest.toml", "paket.lock"}

def is_lockfile(path):
    return os.path.basename(path) in LOCKFILES

# ---------------- (a) path conventions ----------------
# (rule_id, regex over the full repo-relative path). Ordered; first match wins.
PATH_RULES = [
    ("protobuf_py", re.compile(r"_pb2(_grpc)?\.pyi?$")),
    ("protobuf_go", re.compile(r"(\.pb|_grpc\.pb|\.pb\.gw|\.pb\.validate|_vtproto\.pb)\.go$")),
    ("protobuf_cpp", re.compile(r"\.pb\.(cc|h)$")),
    ("protobuf_js_ts", re.compile(r"(_pb|_grpc_pb|_grpc_web_pb|_connect)\.(js|d\.ts|ts)$")),
    ("protobuf_dart", re.compile(r"\.pb(enum|json|grpc|server)?\.dart$")),
    ("protobuf_swift", re.compile(r"\.(pb|grpc)\.swift$")),
    ("k8s_zz_generated", re.compile(r"(^|/)zz_generated[^/]*$")),
    ("dot_generated", re.compile(r"[._]generated\.[A-Za-z0-9]+$")),      # foo.generated.ts, foo_generated.go
    ("dot_gen", re.compile(r"\.gen\.[A-Za-z0-9]+$")),                    # foo.gen.go, routeTree.gen.ts
    ("go_underscore_gen", re.compile(r"_gen\.go$")),                     # wire_gen.go, msgp *_gen.go
    ("sqlc_go", re.compile(r"\.sql\.go$")),
    ("dart_build_runner", re.compile(r"\.(g|freezed|gr|mocks|config|chopper|reflectable)\.dart$")),
    ("dotnet_designer", re.compile(r"\.[Dd]esigner\.(cs|vb)$")),
    ("dotnet_g_cs", re.compile(r"\.g(\.i)?\.cs$")),
    ("generated_dir", re.compile(r"(^|/)(generated|__generated__|autogen|auto_generated|auto-generated|_generated)(/)")),
]

def path_rule(path):
    if is_lockfile(path): return None
    for rid, rx in PATH_RULES:
        if rx.search(path): return rid
    return None

# ---------------- (b) header markers ----------------
HDR_GO = re.compile(r"Code generated .* DO NOT EDIT")                      # Go convention (golang.org/s/generatedcode)
HDR_AT = re.compile(r"@generated\b")                                         # Meta/Facebook convention
HDR_CS = re.compile(r"<auto-generated", re.I)                                # .NET convention
HDR_GEN = re.compile(r"generat", re.I)
HDR_NOEDIT = re.compile(r"(do not (edit|modify)|don'?t (edit|modify)|changes (to this file )?(will|may) (be lost|cause)|will be (overwritten|lost)|manual (changes|edits|modifications)|edits? (will|may) be (overwritten|lost))", re.I)
HDR_WEAK = re.compile(r"(auto-?generated|automatically generated|this (file|code) (was|is|has been) (auto(matically)?[- ])?generated|generated (by|from|with|using) )", re.I)

def header_class(lines):
    """lines: the first <=15 lines of a file. Returns 'strong', 'weak' or None.
    strong = Go marker, @generated, <auto-generated>, or a 'generat*' word plus a do-not-edit phrase in the window."""
    w = "\n".join(lines[:15])
    if HDR_GO.search(w) or HDR_AT.search(w) or HDR_CS.search(w): return "strong"
    if HDR_GEN.search(w) and HDR_NOEDIT.search(w): return "strong"
    if HDR_WEAK.search(w): return "weak"
    return None

HUNK = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")

def patch_top(patch, status):
    """Reconstruct what the patch reveals about lines 1..15 of the NEW and OLD file.
    Returns (new_top_lines or None, new_top_complete, old_top_lines or None, old_top_complete).
    'complete' means the patch shows every line in 1..min(15, file length) (file added, or a hunk starting at
    line 1 with >=15 new-side lines or covering the whole added file)."""
    new, old = {}, {}
    new_complete = old_complete = False
    ln_new = ln_old = 0; first = True
    for raw in patch.split("\n"):
        m = HUNK.match(raw)
        if m:
            ln_old, ln_new = int(m.group(1)), int(m.group(3))
            n_new = int(m.group(4)) if m.group(4) is not None else 1
            n_old = int(m.group(2)) if m.group(2) is not None else 1
            if first:
                if ln_new <= 1 and (n_new >= 15 or status == "added"): new_complete = True
                if ln_old <= 1 and (n_old >= 15 or status == "removed"): old_complete = True
                first = False
            continue
        if first: continue
        if raw.startswith("+"):
            if ln_new <= 15: new[ln_new] = raw[1:]
            ln_new += 1
        elif raw.startswith("-"):
            if ln_old <= 15: old[ln_old] = raw[1:]
            ln_old += 1
        elif raw.startswith("\\"):
            continue
        else:
            t = raw[1:] if raw.startswith(" ") else raw
            if ln_new <= 15: new[ln_new] = t
            if ln_old <= 15: old[ln_old] = t
            ln_new += 1; ln_old += 1
        if ln_new > 15 and ln_old > 15 and not raw.startswith(("+", "-", " ")): pass
    nl = [new[k] for k in sorted(new)] if new else None
    ol = [old[k] for k in sorted(old)] if old else None
    return nl, new_complete, ol, old_complete

def header_from_patch(patch, status):
    """Returns (cls, coverage): cls in {'strong','weak',None}; coverage in {'complete','partial','none'} for the
    new-side (or old side for removed files) top window. Marker search uses both sides' visible top lines."""
    if not patch: return None, "none"
    nl, nc, ol, oc = patch_top(patch, status)
    c1 = header_class(nl) if nl else None
    c2 = header_class(ol) if ol else None
    cls = "strong" if "strong" in (c1, c2) else ("weak" if "weak" in (c1, c2) else None)
    cov = "complete" if (nc or oc) else ("partial" if (nl or ol) else "none")
    return cls, cov

# ---------------- plausible sources ----------------
IDL_EXT = {".proto", ".thrift", ".avsc", ".avdl", ".fbs", ".capnp", ".graphql", ".graphqls", ".gql", ".prisma", ".smithy",
           ".xsd", ".wsdl", ".raml", ".resx", ".settings", ".xaml", ".ui", ".edmx", ".tt", ".sql", ".tmpl", ".tpl", ".j2",
           ".jinja", ".jinja2", ".mustache", ".hbs", ".handlebars", ".ejs", ".liquid", ".stg", ".cue", ".jsonschema", ".kdl", ".arb",
           ".g4", ".lark", ".y", ".l", ".rl", ".peg", ".pest", ".ne"}
SPEC_RX = re.compile(r"(openapi|swagger|schema|asyncapi|\bapi[-_.]?spec|\.spec\.(ya?ml|json)$|(^|/)specs?/)", re.I)
SPEC_EXT = (".yaml", ".yml", ".json", ".json5", ".toml")
CONFIG_NAMES = {"buf.gen.yaml", "buf.yaml", "buf.work.yaml", "buf.gen.yml", "codegen.ts", "codegen.yml", "codegen.yaml",
                "codegen.json", "codegen.js", "sqlc.yaml", "sqlc.yml", "sqlc.json", "gqlgen.yml", "gqlgen.yaml", "openapitools.json",
                ".openapi-generator-ignore", "build.yaml", "pubspec.yaml", "Makefile", "makefile", "GNUmakefile", "justfile",
                "Taskfile.yml", "Taskfile.yaml", "tsr.config.json", "orval.config.ts", "orval.config.js", "kubebuilder.yaml",
                "PROJECT", "wire.go", "gen.go", "generate.go", "doc.go", "tools.go", "ent/generate.go", "turbo.json",
                "openapi-ts.config.ts", "graphql.config.yml", "graphql.config.ts", ".graphqlrc.yml", ".graphqlrc", "drizzle.config.ts",
                "swagger.yaml", "swagger.json", "openapi.yaml", "openapi.json"}
SCRIPT_EXT = (".py", ".sh", ".go", ".js", ".ts", ".mjs", ".cjs", ".rb", ".pl", ".ps1", ".bash", ".rs", ".kt", ".java", ".cs", ".dart")
GENSCRIPT_RX = re.compile(r"(^|[/_\-.])(gen|generate|generator|generators|codegen|regen|build_runner|scaffold)([/_\-.]|$)", re.I)

GEN_SUFFIX = [re.compile(r"_pb2(_grpc)?\.pyi?$"), re.compile(r"(\.pb|_grpc\.pb|\.pb\.gw|\.pb\.validate)\.go$"),
              re.compile(r"\.(g|freezed|gr|mocks|config|chopper)\.dart$"), re.compile(r"\.[Dd]esigner\.(cs|vb)$"),
              re.compile(r"\.g(\.i)?\.cs$"), re.compile(r"[._]generated(\.[A-Za-z0-9]+)$"), re.compile(r"\.gen(\.[A-Za-z0-9]+)$"),
              re.compile(r"_gen\.go$"), re.compile(r"\.sql\.go$")]

def stem_of_generated(path):
    b = os.path.basename(path)
    for rx in GEN_SUFFIX:
        m = rx.search(b)
        if m: return b[:m.start()]
    return None

def is_plausible_source(f, gen_path):
    """Could f (another file changed in the same PR) be an input/config/generator of gen_path? Deliberately generous,
    so that 'generated-without-source' is a conservative (lower-bound-like) set."""
    if f == gen_path or is_lockfile(f) or path_rule(f): return False
    b = os.path.basename(f); ext = os.path.splitext(b)[1].lower()
    if ext in IDL_EXT: return True
    if b in CONFIG_NAMES or f in CONFIG_NAMES or b.endswith(".mk"): return True
    if ext in SPEC_EXT and SPEC_RX.search(f): return True
    if ext in SCRIPT_EXT and GENSCRIPT_RX.search(f): return True
    gd, fd = os.path.dirname(gen_path), os.path.dirname(f)
    st = stem_of_generated(gen_path)
    if st and fd == gd and (b.startswith(st + ".") or os.path.splitext(b)[0] == st): return True   # foo.g.dart <- foo.dart
    if re.search(r"(^|/)zz_generated", gen_path) and fd == gd and ext == ".go": return True          # deepcopy <- types.go
    if gen_path.endswith((".designer.cs", ".Designer.cs", ".designer.vb", ".Designer.vb")) and fd == gd and ext in (".resx", ".settings", ".cs", ".vb", ".xaml"): return True
    return False
