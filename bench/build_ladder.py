"""Build the signal-ladder variants of the test-split regen and mixed tasks into bench/tasks_ladder/.

For every test task of kind regen or mixed (13 tasks) we build three counterfactual variants from the SAME
task definition (same repo, same issue, same tests, same reference fix):
  L0: generated files carry no generator header; no AGENTS.md.
  L1: generated files carry the generator's real header (or, where the original task disabled it, the family's
      standard header); no AGENTS.md.
  L2: L1 plus AGENTS.md with the benchmark's standard contributor note (same text as the existing AGENTS.md tasks).
Per family:
  jinja    : header lives in the templates (original header=True text "... DO NOT EDIT." vs neutral line).
  openapi  : datamodel-codegen default header vs --custom-file-header '# Billing API models' (as in the original tasks).
  protected: generator script emits the header lines; L0 replaces them with a neutral line.
  protobuf, lark: the generator always emits a header, so L0 adds a post-processing step to the gen recipe
             (tools/postprocess.py) that removes the leading banner lines. Residual signals that L0 does NOT remove
             (reported, not hidden): protobuf file names (*_pb2.py) and the Lark MPL license paragraph that mentions
             "generated code".
The original tasks in bench/tasks are not modified. Every variant is validated with the same oracle checks as
bench/build.py (untouched fails; reference fix passes immediate+durable; generated-only patch passes immediate and
fails durable). Usage: python bench/build_ladder.py [task_id ...]
"""
import copy, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE))
import bench.build as B
from bench.families import TASKS, AGENTS_GENERIC, d

OUT = os.path.join(HERE, "tasks_ladder")
GEN_DIR = {"protobuf": "gen/", "openapi": "client/models.py", "jinja": "app/settings.py and app/flags.py",
           "lark": "calc/_parser.py", "protected": "models/entities.py (outside USER CODE regions)"}
JJ_HDR = [("# This file is rendered from templates/settings.py.j2 by tools/render.py. DO NOT EDIT.\n", "# Application settings.\n"),
          ("# Rendered from templates/flags.py.j2 by tools/render.py. DO NOT EDIT.\n", "# Feature flags.\n")]
OA_CUSTOM = " --custom-file-header '# Billing API models'"
PR_HDR = ('lines = ["# Generated by tools/gen_entities.py from model/entities.yaml.",\n'
          '         "# Only code inside BEGIN/END USER CODE regions is preserved when regenerating.",\n')
PR_NEUTRAL = 'lines = ["# Catalog entities.",\n'
POSTPROCESS = d('''
    """Post-process generated modules: normalize the file preamble (removes the leading banner comment lines)."""
    import re, sys
    STRIP = re.compile(r'^(# .*(generat|DO NOT EDIT|GENCODE|source:|Protobuf Python Version|Git:|Author:).*|# -+|"""Generated protocol buffer code\\."""|#)$', re.I)
    for path in sys.argv[1:]:
        lines = open(path).read().split("\\n")
        out = [l for i, l in enumerate(lines) if not (i < 12 and STRIP.match(l))]
        open(path, "w").write("\\n".join(out))
''')

def set_header(t, on):
    f = t["files"]; fam = t["family"]
    if fam == "jinja":
        for k in ("templates/settings.py.j2", "templates/flags.py.j2"):
            for h, n in JJ_HDR: f[k] = f[k].replace(n, h) if on else f[k].replace(h, n)
    elif fam == "openapi":
        f["Makefile"] = f["Makefile"].replace(OA_CUSTOM, "") if on else (f["Makefile"] if OA_CUSTOM in f["Makefile"] else f["Makefile"].replace("--formatters black isort", "--formatters black isort" + OA_CUSTOM))
    elif fam == "protected":
        if not on:
            assert PR_HDR in f["tools/gen_entities.py"]; f["tools/gen_entities.py"] = f["tools/gen_entities.py"].replace(PR_HDR, PR_NEUTRAL)
    elif fam in ("protobuf", "lark"):
        if not on:
            f["tools/postprocess.py"] = POSTPROCESS
            lines = f["Makefile"].split("\n"); i = lines.index("gen:")
            lines.insert(i + 2, "\tpython tools/postprocess.py " + " ".join(t["generated"]))
            f["Makefile"] = "\n".join(lines)
            t["generators"] = t.get("generators", []) + ["tools/postprocess.py"]
    else:
        raise ValueError(fam)
    t["header"] = on

def variant(t0, level):
    t = copy.deepcopy(t0); t["id"] = f"{t0['id']}__L{level}"; t["ladder_level"] = level; t["ladder_base"] = t0["id"]
    set_header(t, level >= 1)
    t["files"].pop("AGENTS.md", None)
    if level == 2: t["files"]["AGENTS.md"] = AGENTS_GENERIC.format(gen_dir=GEN_DIR[t["family"]])
    t["agents_md"] = level == 2
    return t

if __name__ == "__main__":
    only = sys.argv[1:]
    B.OUT = OUT; os.makedirs(OUT, exist_ok=True)
    base = [t for t in TASKS if t["split"] == "test" and t["kind"] in ("regen", "mixed")]
    rows, index = [], {}
    from genlineage.agent import looks_generated
    for t0 in base:
        for lvl in (0, 1, 2):
            t = variant(t0, lvl)
            if only and t["id"] not in only and t0["id"] not in only: continue
            meta, repo = B.build_one(t); r = B.validate(meta, repo)
            heads = {g: "\n".join(open(os.path.join(repo, g)).read().splitlines()[:15]) for g in t["generated"]}
            r["headerguard_visible"] = {g: looks_generated(repo, g) for g in t["generated"]}
            r["header_first_line"] = {g: h.splitlines()[0] if h else "" for g, h in heads.items()}
            rows.append(r); print(json.dumps(r), flush=True)
            index[t["id"]] = {k: t[k] for k in ("family", "split", "kind", "fix_locus", "header", "agents_md", "ladder_level", "ladder_base")}
    if not only:
        json.dump(index, open(os.path.join(OUT, "index.json"), "w"), indent=1)
        json.dump(rows, open(os.path.join(OUT, "validation.json"), "w"), indent=1)
    bad = [r["task"] for r in rows if not r["ok"]]
    print("ALL OK" if not bad else f"FAILED: {bad}", len(rows))
