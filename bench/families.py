JJ_RENDER = d("""
    \"\"\"Render app/settings.py and app/flags.py from config/*.yaml using templates/*.j2.\"\"\"
    import os, yaml, jinja2
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(os.path.join(ROOT, "templates")), keep_trailing_newline=True)
    ctx = {}
    for name in ("settings", "features"):
        with open(os.path.join(ROOT, "config", name + ".yaml")) as f:
            ctx[name] = yaml.safe_load(f)
    for tpl, out in (("settings.py.j2", "app/settings.py"), ("flags.py.j2", "app/flags.py")):
        text = env.get_template(tpl).render(**ctx)
        with open(os.path.join(ROOT, out), "w") as f:
            f.write(text)
""")
def jj_settings_tpl(header=True, bool_ok=True):
    h = "# This file is rendered from templates/settings.py.j2 by tools/render.py. DO NOT EDIT.\n" if header else "# Application settings.\n"
    b = "{{ value }}" if bool_ok else "\"{{ value }}\""
    return h + d("""
        {% for key, value in settings.items() -%}
        {% if value is boolean -%}
        """) + f"{{{{ key | upper }}}} = {b}\n" + d("""
        {% elif value is string -%}
        {{ key | upper }} = {{ value | tojson }}
        {% else -%}
        {{ key | upper }} = {{ value }}
        {% endif -%}
        {% endfor %}
    """)
def jj_flags_tpl(header=True, all_ok=True):
    h = "# Rendered from templates/flags.py.j2 by tools/render.py. DO NOT EDIT.\n" if header else "# Feature flags.\n"
    sl = "features" if all_ok else "features[:-1]"
    return h + d("""
        ENABLED = frozenset({
        {%- for f in """ + sl + """ %}
            {{ f | tojson }},
        {%- endfor %}
        })
        """) + "\n\ndef is_enabled(name):\n    return name in ENABLED\n"
