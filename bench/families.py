"""GenLineage-Bench task definitions.

Each task is a small, realistic Python repository in which some files are produced by a
generator. A task records ground truth used ONLY for scoring and validation (never shown to
agents and never read by LineageGuard): the generation command, the generated paths, the
reference fix, and (for regeneration tasks) a plausible patch to the generated file that
passes the tests immediately but is lost on regeneration.

kind = "regen"     : the correct fix lives upstream of a generated file (spec, template, grammar, generator).
kind = "inregion"  : the correct fix is inside a preserved user region of a generated file (editing the
                     generated file IS correct; a blanket "never edit generated files" rule fails here).
kind = "control"   : the bug is in hand-owned code next to generated code; editing generated inputs is wrong.
"""
import json, textwrap

def d(s):
    return textwrap.dedent(s).lstrip("\n")

AGENTS_GENERIC = d("""
    # Contributor notes
    - Files under `{gen_dir}` are generated by `make gen`. Do not edit them by hand; change the inputs listed in the
      Makefile and regenerate. CI runs `make gen` from a clean checkout before the tests.
    - Run the tests with `make test`.
""")

def makefile(gen_lines, extra=""):
    return "gen:\n" + "".join("\t" + l + "\n" for l in gen_lines) + "\ntest:\n\tpython -m unittest discover -s tests -v\n" + extra

TASKS = []
def task(**kw):
    kw.setdefault("gen_cmd", "make gen")
    TASKS.append(kw)

