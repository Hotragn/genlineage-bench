"""Generate models/entities.py from model/entities.yaml.

Code between `# BEGIN USER CODE <name>` and `# END USER CODE <name>` is preserved across
regenerations; everything else is overwritten.
"""
import os, re, yaml
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "models/entities.py")
spec = yaml.safe_load(open(os.path.join(ROOT, "model/entities.yaml")))
old = open(OUT).read() if os.path.exists(OUT) else ""
kept = dict(re.findall(r"# BEGIN USER CODE (\w+)\n(.*?)    # END USER CODE \1", old, re.S))
lines = ["# Generated by tools/gen_entities.py from model/entities.yaml.",
         "# Only code inside BEGIN/END USER CODE regions is preserved when regenerating.",
         "from dataclasses import dataclass, field", ""]
for ent in spec["entities"]:
    name = ent["name"]
    lines += ["", "@dataclass", f"class {name}:"]
    for f in ent["fields"]:
        default = f" = {f['default']!r}" if "default" in f else ""
        lines.append(f"    {f['name']}: {f['type']}{default}")
    lines += ["", f"    # BEGIN USER CODE {name}"]
    body = kept.get(name, "    def validate(self):\n        return True\n")
    lines.append(body.rstrip("\n"))
    lines += [f"    # END USER CODE {name}", ""]
open(OUT, "w").write("\n".join(lines) + "\n")
