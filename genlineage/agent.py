"""Minimal tool-calling repair agent over an ollama /api/chat backend, with pluggable tool-layer
conditions. One matched config for every model (see CONFIG)."""
import json, os, re, shutil, tempfile, time, urllib.request
from genlineage.env import sh, TEST_CMD
from genlineage import lineage as L

OLLAMA = os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434")
LIN_CONDS = ("lineage", "gate", "full", "verify", "staticblock")
CONFIG = dict(temperature=0.7, num_ctx=16384, num_predict=2048, think=False, max_steps=25, max_nudges=2, max_tool_out=4000, max_verify_rounds=2)

SYSTEM = ("You are an autonomous coding agent working inside a Python repository (the current directory). "
          "Use the tools to investigate the repository and fix the reported issue. "
          "When you are finished, reply with a short summary of what you changed and make no further tool calls.")
HINT = (" Note: some files in this repository may be produced by code generators. Do not hand-edit generated files; "
        "change the inputs they are generated from (specs, templates, schemas, generator scripts) and re-run the project's generation command.")

def fn(name, desc, props):
    return {"type": "function", "function": {"name": name, "description": desc,
            "parameters": {"type": "object", "properties": {k: {"type": "string", "description": v} for k, v in props.items()}, "required": list(props)}}}
TOOLS = [
    fn("list_files", "List all files in the repository (recursive).", {}),
    fn("read_file", "Read a text file.", {"path": "Path relative to the repo root"}),
    fn("write_file", "Create or overwrite a file with the given full content.", {"path": "Path relative to the repo root", "content": "Full new file content"}),
    fn("replace_in_file", "Replace an exact substring in a file (first occurrence).", {"path": "Path relative to the repo root", "old": "Exact text to replace", "new": "Replacement text"}),
    fn("run_tests", "Run the test suite (python -m unittest discover -s tests -v).", {}),
    fn("run_command", "Run a shell command in the repo root (60 s timeout), e.g. `make gen`, `grep -n x file`.", {"command": "Shell command"}),
]
BLOCK = re.compile(r"\b(sudo|curl|wget|ssh|scp|pip|apt|git\s+push)\b|\.\.|~|\$HOME|\$\{?PWD|(^|[\s='\"(])/(?!dev/null)")

# HeaderGuard baseline: re-implementation of the detector rules documented for dsh-protect-generated-files v0.2
# (header regex over the first 15 lines, known protobuf output names; deny with a hint; identical retry allowed once;
# also guards sed -i, perl -pi, > and tee on such files).
HDR = re.compile(r"(code generated .*do not edit|@generated|do not edit|auto-generated|this file was generated|<auto-generated>|generated by \S+)", re.I)
HDR_OK = re.compile(r"(edit freely|safe to edit|do not edit without|generated by (hand|chatgpt))", re.I)
def looks_generated(repo, rel):
    if re.search(r"(_pb2\.py|_pb2_grpc\.py|\.pb\.go)$", rel): return True
    p = os.path.join(repo, rel)
    if not os.path.isfile(p): return False
    head = "\n".join(open(p, errors="replace").read().splitlines()[:15])
    return bool(HDR.search(head)) and not HDR_OK.search(head)
SHELL_TARGETS = [re.compile(r"sed\s+-i\S*\s.*?(\S+)\s*$"), re.compile(r"perl\s+-p?i\S*\s.*?(\S+)\s*$"), re.compile(r">>?\s*(\S+)"), re.compile(r"tee\s+(?:-a\s+)?(\S+)")]

def safe(repo, path):
    p = os.path.realpath(os.path.join(repo, path or "."))
    if not (p == os.path.realpath(repo) or p.startswith(os.path.realpath(repo) + os.sep)): raise ValueError("path escapes repository")
    return p

class Tools:
    def __init__(self, repo, cond, lin):
        self.repo, self.cond, self.lin = repo, cond, lin
        self.R = cond in ("lineage", "gate", "full"); self.G = cond in ("gate", "full"); self.V = cond in ("verify", "full")
        self.static = cond == "staticblock"; self.Vt = cond == "verify_tests"
        self.guard = cond == "headerguard"; self.denied = set(); self.events = []
    def banner(self, rel):
        o = self.lin["outputs"].get(rel) if self.lin else None
        if not o: return ""
        srcs = ", ".join(o["specs"] + o["generators"]) or "(the generation command itself)"
        return (f"[lineage] {rel} is written by `{o['command']}` from: {srcs}. "
                f"Edits to this file are overwritten when `{o['command']}` runs, except text the generator preserves.\n")
    def check_write(self, rel, new_text):
        if self.guard and looks_generated(self.repo, rel):
            key = (rel, new_text)
            if key in self.denied: self.events.append(("guard_retry_allowed", rel)); return None
            self.denied.add(key); self.events.append(("guard_block", rel))
            return (f"BLOCKED: {rel} looks generated (its header or file name says so). A hand edit will be overwritten the next time it is "
                    f"regenerated. Instead: edit its source inputs and run the project's generator. If a hand edit is truly right, repeat the identical call once to confirm.")
        if (self.G or self.static) and self.lin and rel in self.lin["outputs"]:
            o = self.lin["outputs"][rel]; p = os.path.join(self.repo, rel)
            old = open(p, errors="replace").read() if os.path.exists(p) else ""
            srcs = ", ".join(o["specs"] + o["generators"]) or o["command"]
            ptr = L.pointer(self.lin, rel, old, new_text)
            if self.static:
                self.events.append(("static_reject", rel))
                return (f"REJECTED (file unchanged): {rel} is generated by `{o['command']}` from {srcs}. Edits to generated files are not allowed."
                        f"{ptr} Make the change in the inputs ({srcs}) and run `{o['command']}`.")
            ok, detail = L.edit_survives(self.repo, o["command"], rel, new_text, old_text=old)
            self.events.append(("gate_" + ("pass" if ok else "reject"), rel))
            if not ok:
                return (f"REJECTED (file unchanged): {rel} is generated by `{o['command']}` from {srcs}. A shadow regeneration shows this edit "
                        f"would be lost ({detail}).{ptr} Make the change in the inputs ({srcs}) and run `{o['command']}`.")
        return None
    def __call__(self, name, a, log):
        repo = self.repo
        try:
            if name == "list_files":
                out = []
                for d, dirs, fs in os.walk(repo):
                    dirs[:] = [x for x in dirs if x not in ("__pycache__", ".git")]
                    for f in fs:
                        rel = os.path.relpath(os.path.join(d, f), repo); tag = ""
                        if self.R and self.lin and rel in self.lin["outputs"]: tag = f"   [generated by `{self.lin['outputs'][rel]['command']}`]"
                        out.append(rel + tag)
                return "\n".join(sorted(out))
            if name == "read_file":
                p = safe(repo, a.get("path", "")); rel = os.path.relpath(p, repo)
                return (self.banner(rel) if self.R else "") + open(p, errors="replace").read()
            if name in ("write_file", "replace_in_file"):
                p = safe(repo, a.get("path", "")); rel = os.path.relpath(p, repo)
                if name == "write_file": new = "".join(l for l in a.get("content", "").splitlines(True) if not l.startswith("[lineage] "))
                else:
                    s = open(p).read()
                    if not a.get("old") or a["old"] not in s: return "ERROR: old text not found in file"
                    new = s.replace(a["old"], a.get("new", ""), 1)
                msg = self.check_write(rel, new)
                if msg: log["blocked_writes"].append(rel); return msg
                os.makedirs(os.path.dirname(p), exist_ok=True); open(p, "w").write(new); log["edits"].append(rel)
                return f"wrote {rel}" if name == "write_file" else f"replaced in {rel}"
            if name == "run_tests":
                rc, out = sh(TEST_CMD, repo); return f"exit={rc}\n{out}"
            if name == "run_command":
                c = a.get("command", "")
                if BLOCK.search(c): return "ERROR: command not allowed in sandbox"
                if self.guard:
                    for rx in SHELL_TARGETS:
                        for m in rx.finditer(c):
                            tgt = m.group(1).strip("'\";")
                            if looks_generated(repo, tgt):
                                self.events.append(("guard_block_shell", tgt))
                                return f"BLOCKED: this command edits {tgt}, which looks generated. Edit its source inputs and run the generator instead."
                from genlineage.score import digest
                log["commands"].append(c); pre = digest(repo)
                keep = {k: open(os.path.join(repo, k), "rb").read() for k in (self.lin or {}).get("outputs", {}) if os.path.exists(os.path.join(repo, k))} if (self.G or self.static) else {}
                rc, out = sh(c, repo, timeout=60); post = digest(repo)
                changed = sorted(k for k in set(pre) | set(post) if pre.get(k) != post.get(k))
                is_regen = any(rc_cmd in c for rc_cmd in (self.lin or {}).get("commands", [])) or "make gen" in c
                if changed: log["shell_changes"].append({"command": c, "files": changed, "regen": is_regen})
                note = ""
                if keep and not is_regen:
                    for k in [k for k in changed if k in keep]:
                        o = self.lin["outputs"][k]; newt = open(os.path.join(repo, k), errors="replace").read(); oldt = keep[k].decode(errors="replace")
                        ok = (not self.static) and L.edit_survives(repo, o["command"], k, newt, old_text=oldt)[0]
                        if not ok:
                            open(os.path.join(repo, k), "wb").write(keep[k]); self.events.append(("shell_revert", k))
                            note += (f"\nREVERTED: this command modified {k}, which is generated by `{o['command']}`; the change would be lost on regeneration."
                                     f"{L.pointer(self.lin, k, oldt, newt)} Make the change in its inputs instead.")
                return f"exit={rc}\n{out}{note}"
            return f"ERROR: unknown tool {name}"
        except Exception as e:
            return f"ERROR: {type(e).__name__}: {e}"
    def verify(self):
        """Regenerate-then-verify in a shadow copy: run every inferred generation command, then the tests."""
        from genlineage.score import digest
        base = tempfile.mkdtemp(prefix="ver_"); w = os.path.join(base, "r")
        try:
            shutil.copytree(self.repo, w, ignore=shutil.ignore_patterns("__pycache__"))
            pre = digest(w); outs = []
            for cmd in (self.lin or {}).get("commands", []):
                rc, o = sh(cmd, w); outs.append(f"`{cmd}` exit {rc}")
            post = digest(w)
            rewrote = sorted(k for k in post if pre.get(k) != post.get(k) and not (self.lin and self.lin["outputs"].get(k, {}).get("noisy_lines")))
            rc, out = sh(TEST_CMD, w)
            return rc == 0, rewrote, out[-1500:], outs
        finally:
            shutil.rmtree(base, ignore_errors=True)

def chat(model, msgs, seed):
    body = {"model": model, "messages": msgs, "tools": TOOLS, "stream": False, "think": CONFIG["think"],
            "options": {"temperature": CONFIG["temperature"], "seed": seed, "num_ctx": CONFIG["num_ctx"], "num_predict": CONFIG["num_predict"]}}
    req = urllib.request.Request(OLLAMA + "/api/chat", data=json.dumps(body).encode(), headers={"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=1800))

def run(task_dir, model, cond, seed, outdir, lin=None):
    from genlineage.score import score
    meta = json.load(open(os.path.join(task_dir, "task.json"))); orig = os.path.join(task_dir, "repo")
    shutil.rmtree(outdir, ignore_errors=True); os.makedirs(outdir)
    wroot = tempfile.mkdtemp(prefix="glw_"); work = os.path.join(wroot, "repo")
    shutil.copytree(orig, work, ignore=shutil.ignore_patterns("__pycache__"))
    if cond in LIN_CONDS and lin is None: lin = L.infer(work)
    T = Tools(work, cond, lin)
    log = {"task": meta["id"], "model": model, "cond": cond, "seed": seed, "config": CONFIG, "edits": [], "commands": [], "shell_changes": [], "blocked_writes": [], "turns": [], "verify_rounds": []}
    msgs = [{"role": "system", "content": SYSTEM + (HINT if cond == "hint" else "")}, {"role": "user", "content": meta["issue"]}]
    t0 = time.time(); n = 0; nudges = 0; stop = "step_cap"; ptok = etok = 0; ncalls = 0
    while n < CONFIG["max_steps"]:
        n += 1
        try: r = chat(model, msgs, seed)
        except Exception as e: stop = f"api_error: {e}"; break
        ptok += r.get("prompt_eval_count") or 0; etok += r.get("eval_count") or 0
        m = r["message"]; calls = m.get("tool_calls") or []
        turn = {"step": n, "content": m.get("content", ""), "thinking": m.get("thinking", ""), "tool_calls": calls, "results": []}
        msgs.append({"role": "assistant", "content": m.get("content", ""), **({"tool_calls": calls} if calls else {})})
        if not calls:
            log["turns"].append(turn)
            if not (m.get("content") or "").strip() and nudges < CONFIG["max_nudges"]:
                nudges += 1; msgs.pop(); msgs.append({"role": "user", "content": "Continue working on the issue using the tools, or reply with a summary if you are done."}); continue
            if T.Vt and len(log["verify_rounds"]) < CONFIG["max_verify_rounds"]:
                rc_t, out_t = sh(TEST_CMD, work)
                log["verify_rounds"].append({"step": n, "pass": rc_t == 0, "rewrote": []})
                if rc_t != 0:
                    msgs.append({"role": "user", "content": "Completion check: the harness re-ran the tests in a clean copy of your working tree. They FAIL. Fix the root cause.\n" + out_t[-1500:]})
                    continue
            if T.V and len(log["verify_rounds"]) < CONFIG["max_verify_rounds"]:
                ok, rewrote, tail, outs = T.verify()
                log["verify_rounds"].append({"step": n, "pass": ok, "rewrote": rewrote})
                if not ok:
                    lost = (" Regeneration overwrote your changes to: " + ", ".join(rewrote) + ".") if rewrote else ""
                    msgs.append({"role": "user", "content": "Completion check: the harness re-ran the generation commands (" + "; ".join(outs)
                                 + ") in a clean copy of your working tree and re-ran the tests. They FAIL." + lost
                                 + " Fix the root cause in the inputs of the generated files so the fix survives regeneration.\n" + tail})
                    continue
            stop = "model_done"; break
        for c in calls:
            f = c.get("function", {}); args = f.get("arguments") or {}
            if isinstance(args, str):
                try: args = json.loads(args)
                except Exception: args = {}
            out = T(f.get("name"), args if isinstance(args, dict) else {}, log); ncalls += 1
            out = out if len(out) <= CONFIG["max_tool_out"] else out[:CONFIG["max_tool_out"]] + "\n...[truncated]"
            turn["results"].append(out[:2000]); msgs.append({"role": "tool", "content": out, "tool_name": f.get("name")})
        log["turns"].append(turn)
    log.update(steps=n, nudges=nudges, stop=stop, tool_calls=ncalls, prompt_tokens=ptok, gen_tokens=etok, wall_s=round(time.time() - t0, 1),
               guard_events=T.events, lineage_seconds=(lin or {}).get("seconds"))
    shell_hand = [f for ch in log["shell_changes"] if not ch["regen"] for f in ch["files"]]
    log["score"] = score(meta, work, orig, hand_edits=log["edits"] + shell_hand)
    json.dump(log, open(os.path.join(outdir, "transcript.json"), "w"), indent=1)
    shutil.rmtree(wroot, ignore_errors=True)
    return log
